def prepare(root, release, inventory):
    root, release = Path(root).absolute(), Path(release).absolute()
    no_symlink(root)
    no_symlink(release)
    if release.parent != root / 'releases' or not release.name or not release.is_dir():
        raise DeploymentError('Release must be one directory directly inside the dedicated releases tree.')
    for expected in ['bin/unihub', 'web/dist/index.html', 'casdoor-web/index.html',
                     'casdoor-web/swagger/index.html', 'casdoor-web/assets/unihub/unihub-logo-v1.png',
                     'casdoor-web/assets/unihub/unihub-icon-v1.png']:
        if not (release / expected).is_file():
            raise DeploymentError(f'Release is missing required artifact {expected}.')
    shared = root / 'shared'
    credential_path = shared / 'credentials.json'
    no_symlink(credential_path)
    if not credential_path.exists():
        if inventory or (shared.exists() and any(shared.iterdir())):
            raise DeploymentError('Existing resources/configuration require the original credentials.json; refusing secret regeneration.')
        credentials = {'schema_version': 1, 'installation_id': secrets.token_hex(16),
            **{key: secrets.token_hex(32) for key in SECRET_KEYS},
            'owner_id': secrets.token_hex(16), 'acceptance_id': secrets.token_hex(16),
            'organization': 'unihub', 'console_client_id': 'unihub-console',
            'product_client_id': 'superwagie-unihub', 'admin_username': 'admin',
            'admin_organization': 'built-in', 'owner_username': 'owner', 'acceptance_username': 'acceptance'}
    else:
        try:
            credentials = json.loads(credential_path.read_text())
            valid_hex = lambda value, size: isinstance(value, str) and len(value) == size and all(c in '0123456789abcdef' for c in value)
            if (credentials.get('schema_version') != 1 or not valid_hex(credentials.get('installation_id'), 32)
                    or any(not valid_hex(credentials.get(key), 64) for key in SECRET_KEYS)
                    or any(not valid_hex(credentials.get(key), 32) for key in ['owner_id', 'acceptance_id'])):
                raise ValueError()
        except (ValueError, OSError, TypeError):
            raise DeploymentError('Original credentials are invalid/incomplete; restore them without rotating secrets.') from None
    validate_resources(inventory, credentials, root)
    root.mkdir(parents=True, exist_ok=True, mode=0o755)
    root.chmod(0o755)
    private_directory(shared)
    atomic_write(credential_path, json.dumps(credentials, indent=2) + '\n')
    runtime = {'APP_ENV': 'development', 'LISTEN_ADDR': '127.0.0.1:8088',
        'DATABASE_URL': 'postgresql://unihub_app:' + credentials['app_database_password'] + '@127.0.0.1:55438/unihub?sslmode=disable',
        'LEDGER_URL': 'http://127.0.0.1:53068', 'LEDGER_NAME': 'unihub',
        'OIDC_ISSUER': PUBLIC_URL, 'OIDC_AUDIENCE': 'unihub-console',
        'OIDC_PRODUCT_CLIENTS': 'superwagie=superwagie-unihub', 'PUBLIC_URL': PUBLIC_URL,
        'OIDC_CLIENT_SECRET': credentials['client_secret'], 'CONSOLE_STATIC_DIR': str(root / 'current/web/dist'),
        'MODEL_SERVICE_TOKEN': credentials['model_service_token'], 'SANDBOX_CATALOG': 'true',
        'BILLING_OPERATOR_IDS': '', 'OPS_OIDC_AUDIENCE': '', 'PAYMENT_MODE': 'sandbox',
        'PAYMENT_MERCHANT': 'unihub-sandbox', 'PAYMENT_SIGNING_KEY': credentials['payment_signing_key']}
    compose_env = {'UNIHUB_ROOT': str(root), 'RELEASE_DIR': str(release),
        'INSTALLATION_ID': credentials['installation_id'], 'POSTGRES_ADMIN_PASSWORD': credentials['postgres_admin_password'],
        'LEDGER_POSTGRES_URI': 'postgresql://unihub_ledger:' + credentials['ledger_database_password'] + '@unihub-server-postgres:5432/ledger?sslmode=disable'}
    atomic_write(shared / 'runtime.env', env_text(runtime))
