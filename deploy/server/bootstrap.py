def literal(value):
    return "'" + value.replace("'", "''") + "'"


def database_sql(credentials):
    # CREATE DATABASE cannot run inside DO/transaction. psql's \gexec executes
    # each generated statement separately; separate-line terminators work on PG16.
    sql = []
    for role, key in [('unihub_app', 'app_database_password'), ('unihub_ledger', 'ledger_database_password'),
                      ('unihub_casdoor', 'casdoor_database_password')]:
        sql.append(f"DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname={literal(role)}) THEN CREATE ROLE {role} LOGIN PASSWORD {literal(credentials[key])}; END IF; END $$;")
    for database, owner in [('unihub', 'unihub_app'), ('ledger', 'unihub_ledger'), ('casdoor', 'unihub_casdoor')]:
        sql.append(f"SELECT {literal('CREATE DATABASE ' + database + ' OWNER ' + owner)} WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname={literal(database)})\n\\gexec")
        sql.append(f"DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_database d JOIN pg_roles r ON r.oid=d.datdba WHERE d.datname={literal(database)} AND r.rolname={literal(owner)}) THEN RAISE EXCEPTION 'Unexpected UniHub database owner'; END IF; END $$;")
        sql.append(f'REVOKE ALL ON DATABASE {database} FROM PUBLIC;')
        sql.append(f'GRANT CONNECT, TEMPORARY ON DATABASE {database} TO {owner};')
    return '\n'.join(sql) + '\n'


def branding_sql():
    # Built-in objects are initialized by Casdoor itself, then only these exact
    # visual columns change. In particular no auth defaults/keys are replaced.
    columns = {'displayName': 'display_name', 'logo': 'logo', 'logoDark': 'logo_dark',
        'favicon': 'favicon', 'themeData': 'theme_data', 'title': 'title', 'footerHtml': 'footer_html'}
    statements = ['BEGIN;']
    # Enrollment is explicitly closed initially, including Casdoor's built-in
    # administration app. This single authentication field is intentionally
    # tightened; all other built-in authentication defaults remain intact.
    statements.append("UPDATE application SET enable_sign_up=false WHERE owner='admin' AND name='app-built-in';")
    statements.append("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM application WHERE owner='admin' AND name='app-built-in' AND enable_sign_up=false) THEN RAISE EXCEPTION 'Built-in enrollment disable verification failed'; END IF; END $$;")
    for table, names, fields in [('organization', ['unihub', 'built-in'], ORG_BRAND),
                                  ('application', ['app-unihub', 'app-superwagie', 'app-built-in'], APP_BRAND)]:
        assignments = [columns[key] + '=' + literal(json.dumps(value, ensure_ascii=False) if key == 'themeData' else value)
                       + ('::json' if key == 'themeData' else '') for key, value in fields.items()]
        scope = "owner='admin' AND name IN (" + ','.join(literal(n) for n in names) + ')'
        statements.append('UPDATE ' + table + ' SET ' + ','.join(assignments) + ' WHERE ' + scope + ';')
        statements.append(f"DO $$ BEGIN IF (SELECT count(*) FROM {table} WHERE {scope}) <> {len(names)} THEN RAISE EXCEPTION 'UniHub branding targets missing'; END IF; END $$;")
    statements.append("UPDATE application SET homepage_url=CASE name WHEN 'app-built-in' THEN '/login/built-in' ELSE '/login/unihub' END WHERE owner='admin' AND name IN ('app-unihub','app-built-in') AND homepage_url IN ('http://casdoor.org','http://casdoor.org/','https://casdoor.org','https://casdoor.org/','http://casdoor.com','http://casdoor.com/','https://casdoor.com','https://casdoor.com/');")
    upstream = 'https://cdn.casbin.org/img/casbin.svg'
    statements.append('UPDATE organization SET default_avatar=' + literal(BRAND_ICON) +
        " WHERE owner='admin' AND name IN ('unihub','built-in') AND (default_avatar IS NULL OR default_avatar IN (''," + literal(upstream) + '));')
    statements.append('UPDATE "user" SET avatar=' + literal(BRAND_ICON) + " WHERE owner='built-in' AND name='admin' AND avatar=" + literal(upstream) + ';')
    statements.append('COMMIT;')
    return '\n'.join(statements) + '\n'


def psql(sql, database='postgres'):
    run(['docker', 'exec', '-i', 'unihub-server-postgres', 'psql', '-U', 'unihub_admin',
         '-d', database, '-v', 'ON_ERROR_STOP=1', '-q'], input=sql)


def wait_url(url, seconds=180):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=3) as response:
                if response.status == 200:
                    return
        except (OSError, ValueError):
            pass
        time.sleep(2)
    raise DeploymentError('Dependency health timed out; inspect private service state.')


def up(root, release, credentials, inventory):
    compose = ['docker', 'compose', '--project-name', 'unihub-server', '--env-file',
               str(root / 'shared/compose.env'), '-f', str(release / 'deploy/server/compose.yaml')]
    # Explicit env prevents ambient variable overrides from changing the
    # installation identity or publishing a different data/config directory.
    env = {**os.environ, **read_env(root / 'shared/compose.env')}
    run(compose + ['config', '--quiet'], env=env)
    for kind, name in RESOURCES[:3]:
        if kind + ':' + name not in inventory:
            run(['docker', kind, 'create', '--label', MANAGED + '=true', '--label',
                 LABEL + '=' + credentials['installation_id'], name])
    run(compose + ['up', '-d', '--no-deps', 'postgres'], env=env)
    deadline = time.monotonic() + 120
    while time.monotonic() < deadline:
        result = subprocess.run(['docker', 'exec', 'unihub-server-postgres', 'pg_isready', '-U',
            'unihub_admin', '-h', '127.0.0.1', '-d', 'postgres'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if result.returncode == 0:
            break
        time.sleep(2)
    else:
        raise DeploymentError('PostgreSQL health timed out.')
    psql(database_sql(credentials))
    run(compose + ['up', '-d', '--no-deps', 'ledger', 'casdoor'], env=env)
    wait_url('http://127.0.0.1:53068/_info')
    wait_url('http://127.0.0.1:58000/api/health')
    psql(branding_sql(), 'casdoor')
    with urllib.request.urlopen('http://127.0.0.1:58000/.well-known/openid-configuration', timeout=10) as response:
        discovery = json.load(response)
    if (discovery.get('issuer') != PUBLIC_URL or 'RS256' not in discovery.get('id_token_signing_alg_values_supported', [])
            or any(not discovery.get(key, '').startswith(PUBLIC_URL + '/')
                   for key in ['authorization_endpoint', 'token_endpoint', 'jwks_uri'])):
        raise DeploymentError('Casdoor discovery did not confirm the expected HTTPS issuer and RS256 endpoints.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['prepare', 'up'])
    parser.add_argument('--root', type=Path, default=Path('/opt/unihub'))
    parser.add_argument('--release', type=Path, required=True)
    args = parser.parse_args()
    if os.geteuid() != 0:
        raise DeploymentError('Server bootstrap must run as root to protect generated configuration.')
    os.umask(0o077)
    inventory = inventory_resources()
    validate_ports(inventory)
    credentials = prepare(args.root, args.release, inventory)
    print('Private server configuration prepared. Credentials: ' + str(args.root / 'shared/credentials.json'), flush=True)
    if args.mode == 'up':
        up(args.root.absolute(), args.release.absolute(), credentials, inventory)
        print('Dedicated PostgreSQL, ledger and identity dependencies are healthy; HTTPS browser acceptance remains to be checked.', flush=True)


if __name__ == '__main__':
    try:
        main()
    except (DeploymentError, OSError, ValueError) as error:
        # Never echo arbitrary JSON/OS/subprocess values: they can contain secrets.
        message = str(error) if isinstance(error, DeploymentError) else 'Server bootstrap failed; inspect private server configuration.'
        print(message, file=sys.stderr)
        sys.exit(1)
