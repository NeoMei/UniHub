class DeploymentError(Exception):
    pass


def run(args, *, input=None, env=None):
    result = subprocess.run(args, input=input, env=env, text=True, capture_output=True)
    if result.returncode:
        # SQL, Docker diagnostics and application startup can repeat secrets.
        raise DeploymentError(f'{Path(args[0]).name} failed; command output withheld to protect credentials.')
    return result.stdout


def read_env(path):
    values = {}
    for line in path.read_text().splitlines():
        if line and not line.startswith('#'):
            key, value = line.split('=', 1)
            parts = shlex.split(value)
            values[key] = parts[0] if parts else ''
    return values


def no_symlink(path):
    if any(part.is_symlink() for part in [path, *path.parents]):
        raise DeploymentError('Refusing symlink in managed configuration/release path.')


def private_directory(path, mode=0o700, gid=None):
    no_symlink(path)
    path.mkdir(parents=True, exist_ok=True, mode=mode)
    path.chmod(mode)
    if os.geteuid() == 0:
        os.chown(path, 0, gid if gid is not None else 0)


def atomic_write(path, content, mode=0o600, gid=None):
    no_symlink(path)
    if path.exists() and (not path.is_file() or path.stat().st_nlink != 1):
        raise DeploymentError('Refusing non-regular or linked managed configuration.')
    fd, temp = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        os.fchmod(fd, mode)
        if os.geteuid() == 0:
            os.fchown(fd, 0, gid if gid is not None else 0)
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def env_text(values):
    return '# Generated by UniHub server bootstrap. Private; do not commit.\n' + ''.join(
        key + '=' + shlex.quote(value) + '\n' for key, value in values.items())


def resource_missing(kind, name, stderr):
    message = ' '.join(stderr.split()).casefold()
    name = name.casefold()
    # Docker Engine/CLI versions differ in capitalization and wording. Match
    # only a missing response for this exact resource; daemon/permission errors
    # must never be treated as permission to initialize a new installation.
    forms = {
        f'error: no such {kind}: {name}',
        f'error response from daemon: no such {kind}: {name}',
    }
    if kind == 'container':
        forms.update({f'error: no such object: {name}',
                      f'error response from daemon: no such object: {name}'})
    if kind == 'volume':
        forms.add(f'error response from daemon: get {name}: no such volume')
    if kind == 'network':
        forms.add(f'error response from daemon: network {name} not found')
    return message in forms


def inventory_resources():
    run(['docker', 'info', '--format', '{{.ServerVersion}}'])
    inventory = {}
    for kind, name in RESOURCES:
        args = ['docker', 'inspect', '--type', 'container', name] if kind == 'container' else ['docker', kind, 'inspect', name]
        result = subprocess.run(args, capture_output=True, text=True)
        if result.returncode == 0:
            try:
                inventory[kind + ':' + name] = json.loads(result.stdout)[0]
            except (ValueError, IndexError):
                raise DeploymentError('Docker resource inspection returned invalid data.') from None
        elif not resource_missing(kind, name, result.stderr):
            raise DeploymentError('Docker resource inspection failed; no resources changed.')
    return inventory


def validate_resources(inventory, credentials, root):
    for key, resource in inventory.items():
        kind, name = key.split(':', 1)
        labels = (resource.get('Config', {}).get('Labels') if kind == 'container' else resource.get('Labels')) or {}
        if labels.get(LABEL) != credentials['installation_id'] or labels.get(MANAGED) != 'true':
            raise DeploymentError(f'Refusing unmanaged or differently owned resource {name}.')
        if kind != 'container':
            continue
        service = name.removeprefix('unihub-server-')
        if (labels.get('com.docker.compose.project') != 'unihub-server'
                or labels.get('com.docker.compose.service') != service
                or resource.get('Config', {}).get('Image') != IMAGES[service]):
            raise DeploymentError(f'Refusing unexpected container configuration {name}.')
        port, host = {'postgres': ('5432/tcp', '55438'), 'ledger': ('3068/tcp', '53068'), 'casdoor': ('8000/tcp', '58000')}[service]
        bindings = resource.get('HostConfig', {}).get('PortBindings') or {}
        if set(bindings) != {port} or bindings[port] != [{'HostIp': '127.0.0.1', 'HostPort': host}]:
            raise DeploymentError(f'Refusing unexpected port publishing on {name}.')
        networks = resource.get('NetworkSettings', {}).get('Networks', {})
        if set(networks) != {'unihub-server'}:
            raise DeploymentError(f'Refusing unexpected network attachment on {name}.')
        mounts = {m['Destination']: m for m in resource.get('Mounts', [])}
        if service == 'postgres':
            mount = mounts.get('/var/lib/postgresql/data', {})
            if mount.get('Type') != 'volume' or mount.get('Name') != 'unihub-server-postgres':
                raise DeploymentError('PostgreSQL is not using the dedicated persistent volume.')
        if service == 'casdoor':
            conf = mounts.get('/conf', {})
            if conf.get('Type') != 'bind' or conf.get('Source') != str(root / 'shared/casdoor/conf') or conf.get('RW') is not False:
                raise DeploymentError('Casdoor has an unexpected configuration mount.')
            for destination in ['/web/build', '/swagger']:
                mount = mounts.get(destination, {})
                source = Path(mount.get('Source', '/'))
                try:
                    relative = source.relative_to(root / 'releases')
                except ValueError:
                    raise DeploymentError('Casdoor frontend is outside managed releases.') from None
                expected_suffix = ['casdoor-web'] if destination == '/web/build' else ['casdoor-web', 'swagger']
                if (mount.get('Type') != 'bind' or mount.get('RW') is not False
                        or list(relative.parts[1:]) != expected_suffix):
                    raise DeploymentError('Casdoor has an unexpected frontend mount.')
            logs = mounts.get('/logs', {})
            if logs.get('Type') != 'volume' or logs.get('Name') != 'unihub-server-casdoor-logs':
                raise DeploymentError('Casdoor logs are outside the dedicated volume.')


def validate_ports(inventory):
    for service, port in [('postgres', 55438), ('ledger', 53068), ('casdoor', 58000)]:
        if 'container:unihub-server-' + service in inventory:
            continue
        with socket.socket() as sock:
            try:
                sock.bind(('127.0.0.1', port))
            except OSError:
                raise DeploymentError(f'Loopback dependency port {port} is occupied; no service was changed.') from None


