def run(args, *, input=None, env=None):
    result = subprocess.run(args, input=input, env=env, text=True, capture_output=True)
    if result.returncode:
        # SQL, Docker diagnostics and application startup can repeat secrets.
        raise DeploymentError(f'{Path(args[0]).name} failed; command output withheld to protect credentials.')
    return result.stdout


def read_env(path):
    values = {}
    for line in path.read_text().splitlines():
        if line and not line.startswith('#'):
            key, value = line.split('=', 1)
            parts = shlex.split(value)
            values[key] = parts[0] if parts else ''
    return values


def no_symlink(path):
    if any(part.is_symlink() for part in [path, *path.parents]):
        raise DeploymentError('Refusing symlink in managed configuration/release path.')


def private_directory(path, mode=0o700, gid=None):
    no_symlink(path)
    path.mkdir(parents=True, exist_ok=True, mode=mode)
    path.chmod(mode)
    if os.geteuid() == 0:
        os.chown(path, 0, gid if gid is not None else 0)


def atomic_write(path, content, mode=0o600, gid=None):
    no_symlink(path)
    if path.exists() and (not path.is_file() or path.stat().st_nlink != 1):
        raise DeploymentError('Refusing non-regular or linked managed configuration.')
    fd, temp = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        os.fchmod(fd, mode)
        if os.geteuid() == 0:
            os.fchown(fd, 0, gid if gid is not None else 0)
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def env_text(values):
    return '# Generated by UniHub server bootstrap. Private; do not commit.\n' + ''.join(
        key + '=' + shlex.quote(value) + '\n' for key, value in values.items())


def validate_billing_profiles(items):
    """Strict public subset of billing.ParseBillingProfiles and Profile.Validate."""
    def require(condition):
        if not condition:
            raise DeploymentError('Billing profiles rejected; check public schema, composition and positive versions.')

    def exact(value, fields):
        require(isinstance(value, dict) and set(value) == set(fields))

    require(isinstance(items, list) and len(items) <= 100)
    seen = set()
    for item in items:
        require(isinstance(item, dict))
        product = item.get('product_id')
        require(isinstance(product, str) and re.fullmatch(r'[a-z][a-z0-9_-]{0,63}', product) is not None)
        require(product not in seen)
        seen.add(product)
        require(type(item.get('version')) is int and 1 <= item['version'] <= 9223372036854775807)
        if 'preset' in item:
            exact(item, {'product_id', 'version', 'preset'})
            require(item['preset'] in ('hybrid', 'prepaid', 'subscription'))
            continue
        exact(item, {'product_id', 'version', 'subscription', 'included_credits', 'addons', 'usage'})
        for name in ['subscription', 'included_credits', 'addons']:
            exact(item[name], {'enabled'})
            require(type(item[name]['enabled']) is bool)
        usage = item['usage']
        exact(usage, {'enabled', 'require_subscription', 'funding_modes', 'default_funding_mode'})
        require(type(usage['enabled']) is bool and type(usage['require_subscription']) is bool)
        modes = usage['funding_modes']
        require(isinstance(modes, list) and all(isinstance(mode, str) and mode in {'credits', 'prepaid_cash'} for mode in modes))
        require(len(set(modes)) == len(modes) and isinstance(usage['default_funding_mode'], str))
        if usage['enabled']:
            require(bool(modes) and usage['default_funding_mode'] in modes)
        else:
            require(not modes and usage['default_funding_mode'] == '' and not usage['require_subscription'])
        require(not usage['require_subscription'] or item['subscription']['enabled'])
        require(not item['included_credits']['enabled'] or (item['subscription']['enabled'] and 'credits' in modes))
        require(not item['addons']['enabled'] or 'credits' in modes)
    return items


def read_billing_profiles(path):
    path = Path(path)
    no_symlink(path)

    def unique_object(pairs):
        item = {}
        for key, value in pairs:
            if key in item:
                raise DeploymentError('Billing profiles contain duplicate JSON fields.')
            item[key] = value
        return item

    try:
        # O_NONBLOCK prevents a special-file input from hanging a root command.
        fd = os.open(path, os.O_RDONLY | os.O_NONBLOCK | getattr(os, 'O_NOFOLLOW', 0))
        with os.fdopen(fd, 'rb') as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size > 1 << 20:
                raise DeploymentError('Billing profiles require a bounded, unlinked regular file.')
            raw = stream.read((1 << 20) + 1)
        if len(raw) > 1 << 20:
            raise DeploymentError('Billing profiles exceed the public configuration size limit.')
        return validate_billing_profiles(json.loads(raw.decode('utf-8'), object_pairs_hook=unique_object))
    except (OSError, ValueError, UnicodeError, TypeError, RecursionError):
        raise DeploymentError('Billing profiles are unavailable or invalid; no configuration contents were printed.') from None


def staged_billing_path(root):
    path = Path(root) / 'billing-config/products.json'
    no_symlink(path)
    if path.parent.exists() and not path.parent.is_dir():
        raise DeploymentError('Billing configuration directory must be a regular directory.')
    if not path.exists():
        return None
    read_billing_profiles(path)
    return path


def stage_billing(root, source):
    # This opt-in contains no credentials and never touches identity policy/state.
    items = read_billing_profiles(source)
    payload = json.dumps(items, ensure_ascii=False, indent=2) + '\n'
    if len(payload.encode('utf-8')) > 1 << 20:
        raise DeploymentError('Billing profiles exceed the public configuration size limit.')
    public = Path(root) / 'billing-config'
    private_directory(public, 0o755)
    atomic_write(public / 'products.json', payload, 0o644)
    return items


def resource_missing(kind, name, stderr):
    message = ' '.join(stderr.split()).casefold()
    name = name.casefold()
    # Docker Engine/CLI versions differ in capitalization and wording. Match
    # only a missing response for this exact resource; daemon/permission errors
    # must never be treated as permission to initialize a new installation.
    forms = {
        f'error: no such {kind}: {name}',
        f'error response from daemon: no such {kind}: {name}',
    }
    if kind == 'container':
        forms.update({f'error: no such object: {name}',
                      f'error response from daemon: no such object: {name}'})
    if kind == 'volume':
        forms.add(f'error response from daemon: get {name}: no such volume')
    if kind == 'network':
        forms.add(f'error response from daemon: network {name} not found')
    return message in forms


def inventory_resources():
    run(['docker', 'info', '--format', '{{.ServerVersion}}'])
    inventory = {}
    for kind, name in RESOURCES:
        args = ['docker', 'inspect', '--type', 'container', name] if kind == 'container' else ['docker', kind, 'inspect', name]
        result = subprocess.run(args, capture_output=True, text=True)
        if result.returncode == 0:
            try:
                inventory[kind + ':' + name] = json.loads(result.stdout)[0]
            except (ValueError, IndexError):
                raise DeploymentError('Docker resource inspection returned invalid data.') from None
        elif not resource_missing(kind, name, result.stderr):
            raise DeploymentError('Docker resource inspection failed; no resources changed.')
    return inventory


def validate_resources(inventory, credentials, root):
    pin = identity_pin(root)
    if pin and pin.get('installation_id') != credentials['installation_id']:
        raise DeploymentError('Identity image pin belongs to a different installation.')
    for key, resource in inventory.items():
        kind, name = key.split(':', 1)
        labels = (resource.get('Config', {}).get('Labels') if kind == 'container' else resource.get('Labels')) or {}
        if labels.get(LABEL) != credentials['installation_id'] or labels.get(MANAGED) != 'true':
            raise DeploymentError(f'Refusing unmanaged or differently owned resource {name}.')
        if kind != 'container':
            continue
        service = name.removeprefix('unihub-server-')
        allowed_images = {IMAGES[service]}
        if service == 'casdoor' and pin:
            allowed_images = {pin['image_id']}
            if not pin.get('transition_complete', False):
                allowed_images.add(IMAGES[service])
                if pin.get('previous_image_id'):
                    allowed_images.add(pin['previous_image_id'])
        configured_image = resource.get('Config', {}).get('Image')
        if (labels.get('com.docker.compose.project') != 'unihub-server'
                or labels.get('com.docker.compose.service') != service
                or configured_image not in allowed_images
                or (service == 'casdoor' and configured_image.startswith('sha256:') and resource.get('Image') != configured_image)):
            raise DeploymentError(f'Refusing unexpected container configuration {name}.')
        port, host = {'postgres': ('5432/tcp', '55438'), 'ledger': ('3068/tcp', '53068'), 'casdoor': ('8000/tcp', '58000')}[service]
        bindings = resource.get('HostConfig', {}).get('PortBindings') or {}
        if set(bindings) != {port} or bindings[port] != [{'HostIp': '127.0.0.1', 'HostPort': host}]:
            raise DeploymentError(f'Refusing unexpected port publishing on {name}.')
        networks = resource.get('NetworkSettings', {}).get('Networks', {})
        if set(networks) != {'unihub-server'}:
            raise DeploymentError(f'Refusing unexpected network attachment on {name}.')
        mounts = {m['Destination']: m for m in resource.get('Mounts', [])}
        if service == 'postgres':
            mount = mounts.get('/var/lib/postgresql/data', {})
            if mount.get('Type') != 'volume' or mount.get('Name') != 'unihub-server-postgres':
                raise DeploymentError('PostgreSQL is not using the dedicated persistent volume.')
        if service == 'casdoor':
            conf = mounts.get('/conf', {})
            if conf.get('Type') != 'bind' or conf.get('Source') != str(root / 'shared/casdoor/conf') or conf.get('RW') is not False:
                raise DeploymentError('Casdoor has an unexpected configuration mount.')
            for destination in ['/web/build', '/swagger']:
                mount = mounts.get(destination, {})
                source = Path(mount.get('Source', '/'))
                try:
                    relative = source.relative_to(root / 'releases')
                except ValueError:
                    raise DeploymentError('Casdoor frontend is outside managed releases.') from None
                expected_suffix = ['casdoor-web'] if destination == '/web/build' else ['casdoor-web', 'swagger']
                if (mount.get('Type') != 'bind' or mount.get('RW') is not False
                        or list(relative.parts[1:]) != expected_suffix):
                    raise DeploymentError('Casdoor has an unexpected frontend mount.')
            logs = mounts.get('/logs', {})
            if logs.get('Type') != 'volume' or logs.get('Name') != 'unihub-server-casdoor-logs':
                raise DeploymentError('Casdoor logs are outside the dedicated volume.')


def validate_ports(inventory):
    for service, port in [('postgres', 55438), ('ledger', 53068), ('casdoor', 58000)]:
        if 'container:unihub-server-' + service in inventory:
            continue
        with socket.socket() as sock:
            try:
                sock.bind(('127.0.0.1', port))
            except OSError:
                raise DeploymentError(f'Loopback dependency port {port} is occupied; no service was changed.') from None


